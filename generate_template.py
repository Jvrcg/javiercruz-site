def style_header_row(ws, row, n_cols):
    for c in range(1, n_cols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="left", vertical="center")


def style_section_row(ws, row, n_cols):
    for c in range(1, n_cols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = SECTION_FILL
        cell.font = SECTION_FONT


def band_rows(ws, first_row, last_row, n_cols):
    for r in range(first_row, last_row + 1):
        fill = ALT_FILL if (r - first_row) % 2 == 1 else WHITE_FILL
        for c in range(1, n_cols + 1):
            cell = ws.cell(row=r, column=c)
            if cell.font is None or cell.font.name is None:
                cell.font = BASE_FONT
            cell.fill = fill


def autofit(ws, n_cols, max_width=60, sample_rows=200):
    for c in range(1, n_cols + 1):
        col_letter = get_column_letter(c)
        max_len = 0
        for r, cell in enumerate(ws[col_letter]):
            if r > sample_rows and r > 0:
                break
            v = cell.value
            if v is None:
                continue
            l = len(str(v))
            if l > max_len:
                max_len = l
        ws.column_dimensions[col_letter].width = min(max(max_len + 2, 8), max_width)


