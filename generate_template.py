        ws.cell(row=r, column=4,
            value=(f"=COUNTIFS('Raw Data'!$K$2:$K${rd_last},1,"
                   f"'Raw Data'!$G$2:$G${rd_last},TRUE,"
                   f"'Raw Data'!$S$2:$S${rd_last},\">=\"&DATE(2025,{month_num},1),"
                   f"'Raw Data'!$S$2:$S${rd_last},\"<\"&DATE(2025,{month_num + 1},1))"))
